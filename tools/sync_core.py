"""Copy the shared core into every app, or check that the copies are current.

Sao Khue installs an app by copying its own directory, so an app cannot import
`../../core` at runtime. Each app therefore carries a generated copy:

    core/sme_core  ->  apps/<app>/server/sme_core
    core/knowledge ->  apps/<app>/knowledge

Edit only under core/, then run:  python tools/sync_core.py
CI and the tests run:            python tools/sync_core.py --check
"""

from __future__ import annotations

import filecmp
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APPS = ("sme-lending", "sme-sales")
PAIRS = (("core/sme_core", "server/sme_core"), ("core/knowledge", "knowledge"))
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc")
MARKER = "GENERATED.txt"
MARKER_TEXT = "Generated by tools/sync_core.py from {src}. Edit the source, not this copy.\n"


def _files(base: Path) -> set[str]:
    return {
        p.relative_to(base).as_posix()
        for p in base.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc" and p.name != MARKER
    }


def drift() -> list[str]:
    """Every difference between core/ and an app's copy, as readable lines."""
    out = []
    for app in APPS:
        for src_rel, dst_rel in PAIRS:
            src, dst = ROOT / src_rel, ROOT / "apps" / app / dst_rel
            if not dst.exists():
                out.append(f"{app}: missing {dst_rel}")
                continue
            a, b = _files(src), _files(dst)
            out += [f"{app}: {dst_rel}/{f} missing" for f in sorted(a - b)]
            out += [f"{app}: {dst_rel}/{f} not in core" for f in sorted(b - a)]
            out += [f"{app}: {dst_rel}/{f} differs" for f in sorted(a & b)
                    if not filecmp.cmp(src / f, dst / f, shallow=False)]
    return out


def sync() -> None:
    for app in APPS:
        for src_rel, dst_rel in PAIRS:
            src, dst = ROOT / src_rel, ROOT / "apps" / app / dst_rel
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(src, dst, ignore=IGNORE)
            (dst / MARKER).write_text(MARKER_TEXT.format(src=src_rel), encoding="utf-8")


if __name__ == "__main__":
    if "--check" in sys.argv:
        problems = drift()
        print("\n".join(problems) or "core copies are current")
        sys.exit(1 if problems else 0)
    sync()
    print("synced core into: " + ", ".join(APPS))
